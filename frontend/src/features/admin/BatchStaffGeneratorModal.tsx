export function BatchStaffGeneratorModal({
  isOpen,
  onClose,
  onGenerate,
  subjects,
  classes,
  existingCount,
}: Props) {
  const [activeTab, setActiveTab] = useState<'auto_pool' | 'quick_paste'>('auto_pool');
  const [replaceExisting, setReplaceExisting] = useState(false);
  const [maxPerDay, setMaxPerDay] = useState(5);

  // Quick Paste state
  const [pasteText, setPasteText] = useState(
    'Arti Banerjee\nRajesh Verma\nDr. Neha Gupta\nK. Ramanujan\nRitika Sen\nSwati Deshpande\nPriya Venkatesh\nSardar Milkha Singh'
  );
  const [pasteDefaultSubject, setPasteDefaultSubject] = useState<string>('auto_distribute');

  // Calculate teaching demand from classes & subjects
  const demandAnalysis = useMemo(() => {
    const primaryClassesCount = classes.filter(c => c.tier === 'Primary').length;
    const seniorClassesCount = classes.filter(c => c.tier === 'Senior').length;

    const subjectLoads = subjects.map(sub => {
      const primaryTotal = primaryClassesCount * (sub.freqPrimary || 0);
      const seniorTotal = seniorClassesCount * (sub.freqSenior || 0);
      const totalWeeklyPeriods = primaryTotal + seniorTotal;

      // Assuming average 24-28 periods/week per full-time teacher (approx 4-5 periods/day)
      const recommendedTeachers = Math.max(1, Math.ceil(totalWeeklyPeriods / 26));

      return {
        subject: sub,
        primaryTotal,
        seniorTotal,
        totalWeeklyPeriods,
        recommendedTeachers,
      };
    });

    const totalSchoolPeriods = subjectLoads.reduce((sum, s) => sum + s.totalWeeklyPeriods, 0);
    const totalTeachersNeeded = subjectLoads.reduce((sum, s) => sum + s.recommendedTeachers, 0);

    return {
      primaryClassesCount,
      seniorClassesCount,
      subjectLoads,
      totalSchoolPeriods,
      totalTeachersNeeded,
    };
  }, [classes, subjects]);

  // Auto-generated staff list based on demand
  const autoGeneratedTeachers = useMemo(() => {
    const list: Teacher[] = [];
    const usedNames = new Set<string>();
    let genericIdx = 0;

    demandAnalysis.subjectLoads.forEach(({ subject, recommendedTeachers }) => {
      const codeUpper = (subject.code || '').toUpperCase().trim();
      const specificPool = REALISTIC_FACULTY_NAMES[codeUpper] || [];

      for (let i = 0; i < recommendedTeachers; i++) {
        let name = '';
        if (i < specificPool.length && !usedNames.has(specificPool[i])) {
          name = specificPool[i];
        } else if (genericIdx < GENERIC_NAMES.length && !usedNames.has(GENERIC_NAMES[genericIdx])) {
          name = GENERIC_NAMES[genericIdx];
          genericIdx++;
        } else {
          name = `Faculty ${subject.name} #${i + 1}`;
        }
        usedNames.add(name);

        list.push({
          id: `t-auto-${subject.id}-${i}-${Date.now().toString(36)}`,
          name,
          subjects: [subject.id],
          maxPerDay,
          unavailableDays: [],
        });
      }
    });

    return list;
  }, [demandAnalysis, maxPerDay]);

  // Parsed teachers from Quick Paste
  const parsedPastedTeachers = useMemo(() => {
    const lines = pasteText
      .split('\n')
      .map(l => l.trim())
      .filter(Boolean);

    return lines.map((line, idx) => {
      // Support CSV line format "Name, Subject"
      const parts = line.split(/[,|\t]/).map(p => p.trim());
      const name = parts[0];
      let assignedSubjects: string[] = [];

      if (parts[1]) {
        // Try to match subject by name or code
        const matched = subjects.find(
          s =>
            s.name.toLowerCase().includes(parts[1].toLowerCase()) ||
            s.code.toLowerCase() === parts[1].toLowerCase()
        );
        if (matched) assignedSubjects = [matched.id];
      }

      if (assignedSubjects.length === 0) {
        if (pasteDefaultSubject === 'auto_distribute') {
          // Distribute round-robin across subjects
          const sub = subjects[idx % Math.max(1, subjects.length)];
          if (sub) assignedSubjects = [sub.id];
        } else if (pasteDefaultSubject) {
          assignedSubjects = [pasteDefaultSubject];
        } else if (subjects[0]) {
          assignedSubjects = [subjects[0].id];
        }
      }

      return {
        id: `t-paste-${idx}-${Date.now().toString(36)}`,
        name,
        subjects: assignedSubjects,
        maxPerDay,
        unavailableDays: [],
      } as Teacher;
    });
  }, [pasteText, pasteDefaultSubject, subjects, maxPerDay]);

  const activeCandidateList = activeTab === 'auto_pool' ? autoGeneratedTeachers : parsedPastedTeachers;

  const handleExecute = () => {
    if (activeCandidateList.length === 0) return;
    onGenerate(activeCandidateList, replaceExisting);
    onClose();
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/60 backdrop-blur-xs p-4 overflow-y-auto">
      <div className="bg-white rounded-3xl shadow-2xl border border-slate-200 w-full max-w-3xl max-h-[92vh] flex flex-col overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        
        {/* Modal Header */}
        <div className="flex items-center justify-between p-5 border-b border-slate-100 bg-gradient-to-r from-indigo-50/70 via-white to-violet-50/50">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-gradient-to-br from-indigo-600 to-violet-600 flex items-center justify-center text-white shadow-md shadow-indigo-500/20">
              <Users className="w-5 h-5 text-amber-300" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-extrabold text-slate-900 text-base">
                  Fast Faculty Roster Generator
                </h3>
                <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-indigo-100 text-indigo-700">
                  Zero-Excel
                </span>
              </div>
              <p className="text-xs text-slate-500 mt-0.5">
                Generate a curriculum-balanced faculty pool or paste your staff list in seconds.
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-slate-600 hover:bg-slate-100 transition cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Mode Selector Tabs */}
        <div className="flex border-b border-slate-200 bg-slate-50/80 px-5 pt-3 gap-2">
          <button
            type="button"
            onClick={() => setActiveTab('auto_pool')}
            className={`flex items-center gap-2 px-4 py-2.5 rounded-t-xl text-xs font-bold border-b-2 transition cursor-pointer ${
              activeTab === 'auto_pool'
                ? 'border-indigo-600 text-indigo-700 bg-white shadow-2xs'
                : 'border-transparent text-slate-500 hover:text-slate-800'
            }`}
          >
            <Sparkles className="w-3.5 h-3.5 text-amber-500" />
            <span>⚡ 1-Click Balanced Faculty Pool</span>
            <span className="text-[10px] px-1.5 py-0.2 rounded-full bg-indigo-100 text-indigo-700">
              {demandAnalysis.totalTeachersNeeded} Teachers
            </span>
          </button>

          <button
            type="button"
            onClick={() => setActiveTab('quick_paste')}
            className={`flex items-center gap-2 px-4 py-2.5 rounded-t-xl text-xs font-bold border-b-2 transition cursor-pointer ${
              activeTab === 'quick_paste'
                ? 'border-indigo-600 text-indigo-700 bg-white shadow-2xs'
                : 'border-transparent text-slate-500 hover:text-slate-800'
            }`}
          >
            <ClipboardList className="w-3.5 h-3.5 text-slate-500" />
            <span>📋 Multi-Line Quick Paste</span>
            <span className="text-[10px] px-1.5 py-0.2 rounded-full bg-slate-200 text-slate-700">
              {parsedPastedTeachers.length} Parsed
            </span>
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-5 overflow-y-auto space-y-4 text-xs flex-1">
          {activeTab === 'auto_pool' ? (
            <div className="space-y-4">
              {/* Teaching Demand Summary */}
              <div className="p-3.5 rounded-2xl bg-indigo-50/60 border border-indigo-200 space-y-2">
                <div className="flex items-center justify-between">
                  <span className="font-bold text-indigo-950 flex items-center gap-1.5">
                    <Zap className="w-3.5 h-3.5 text-indigo-600 fill-indigo-600" />
                    <span>Curriculum Demand Intelligence</span>
                  </span>
                  <span className="text-[11px] font-semibold text-indigo-700">
                    {classes.length} Classes • {demandAnalysis.totalSchoolPeriods} Periods/Week Required
                  </span>
                </div>
                <p className="text-[11px] text-slate-600">
                  ChronosEdu calculated the exact number of faculty required per subject so every class has qualified instructors and nobody is overloaded.
                </p>

                {/* Subject Department Breakdown Pills */}
                <div className="grid grid-cols-2 sm:grid-cols-3 gap-2 pt-1">
                  {demandAnalysis.subjectLoads.map(({ subject, totalWeeklyPeriods, recommendedTeachers }) => (
                    <div
                      key={subject.id}
                      className="p-2 rounded-xl bg-white border border-indigo-100 flex items-center justify-between"
                    >
                      <div>
                        <div className="font-bold text-slate-900 text-[11px] truncate">{subject.name}</div>
                        <div className="text-[10px] text-slate-400">{totalWeeklyPeriods} periods/wk</div>
                      </div>
                      <span className="font-extrabold text-xs text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded-lg border border-indigo-200">
                        {recommendedTeachers} staff
                      </span>
                    </div>
                  ))}
                </div>
              </div>

              {/* Generated Faculty Roster Preview */}
              <div className="space-y-2">
                <div className="font-bold text-slate-800 flex items-center justify-between">
                  <span>Generated Faculty Directory ({autoGeneratedTeachers.length} Instructors)</span>
                  <span className="text-[11px] text-slate-500 font-normal">Max {maxPerDay} periods/day workload</span>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 max-h-56 overflow-y-auto p-1 bg-slate-50 rounded-2xl border border-slate-200">
                  {autoGeneratedTeachers.map(t => {
                    const sub = subjects.find(s => s.id === t.subjects[0]);
                    return (
                      <div
                        key={t.id}
                        className="p-2.5 rounded-xl bg-white border border-slate-200 flex items-center justify-between shadow-2xs"
                      >
                        <div className="space-y-0.5 truncate">
                          <div className="font-bold text-slate-900 text-xs truncate">{t.name}</div>
                          <span className="text-[10px] font-semibold px-2 py-0.5 rounded-md bg-indigo-50 text-indigo-700 border border-indigo-100">
                            {sub?.name || 'General'}
                          </span>
                        </div>
                        <span className="text-[10px] font-semibold text-slate-500 bg-slate-100 px-2 py-0.5 rounded">
                          ≤ {t.maxPerDay} p/d
                        </span>
                      </div>
                    );
                  })}
                </div>
              </div>
            </div>
          ) : (
            <div className="space-y-4">
              <div className="p-3 rounded-2xl bg-slate-50 border border-slate-200 space-y-1">
                <div className="font-bold text-slate-800 flex items-center gap-1.5">
                  <Info className="w-3.5 h-3.5 text-indigo-600" />
                  <span>Paste Staff Roster</span>
                </div>
                <p className="text-[11px] text-slate-500">
                  Paste faculty names one per line. You can also paste CSV format like <code className="bg-white px-1 rounded border">Arti Banerjee, English</code>.
                </p>
              </div>

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                <div>
                  <label className="block font-bold text-slate-700 mb-1">
                    Default Teaching Subject:
                  </label>
                  <select
                    value={pasteDefaultSubject}
                    onChange={e => setPasteDefaultSubject(e.target.value)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-300 bg-white font-medium text-xs"
                  >
                    <option value="auto_distribute">⚡ Auto-Distribute Across Curriculum</option>
                    {subjects.map(s => (
                      <option key={s.id} value={s.id}>
                        {s.name} ({s.code})
                      </option>
                    ))}
                  </select>
                </div>

                <div>
                  <label className="block font-bold text-slate-700 mb-1">
                    Max Workload (Periods/Day):
                  </label>
                  <select
                    value={maxPerDay}
                    onChange={e => setMaxPerDay(Number(e.target.value) || 5)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-300 bg-white font-medium text-xs"
                  >
                    <option value={4}>4 Periods/Day (Light / Senior Lecturers)</option>
                    <option value={5}>5 Periods/Day (Standard Full-Time)</option>
                    <option value={6}>6 Periods/Day (Maximum Capacity)</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block font-bold text-slate-700 mb-1">
                  Faculty Names (One per line):
                </label>
                <textarea
                  rows={6}
                  value={pasteText}
                  onChange={e => setPasteText(e.target.value)}
                  placeholder="Paste teacher names here..."
                  className="w-full p-3 rounded-xl border border-slate-300 font-mono text-xs bg-white focus:outline-none focus:ring-1 focus:ring-indigo-500"
                />
              </div>

              <div className="space-y-1">
                <span className="font-bold text-slate-700">Preview ({parsedPastedTeachers.length} Parsed):</span>
                <div className="flex flex-wrap gap-1.5 max-h-28 overflow-y-auto p-2 bg-slate-50 rounded-xl border border-slate-200">
                  {parsedPastedTeachers.map((t, idx) => {
                    const sub = subjects.find(s => s.id === t.subjects[0]);
                    return (
                      <span
                        key={idx}
                        className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-white border border-slate-200 text-slate-800 text-[11px] shadow-2xs"
                      >
                        <span className="font-bold">{t.name}</span>
                        <span className="text-[10px] text-indigo-600 font-medium">({sub?.code || 'Gen'})</span>
                      </span>
                    );
                  })}
                </div>
              </div>
            </div>
          )}

          {/* Replacement vs Append Option */}
          {existingCount > 0 && (
            <div className="p-3 rounded-2xl bg-amber-50 border border-amber-200 flex items-center justify-between">
              <div className="space-y-0.5">
                <span className="font-bold text-amber-950 text-xs block">
                  Existing Faculty Roster ({existingCount} Staff Members)
                </span>
                <span className="text-[11px] text-amber-700">
                  Choose whether to replace existing records or append new teachers to your current roster.
                </span>
              </div>
              <label className="flex items-center gap-2 cursor-pointer bg-white px-3 py-1.5 rounded-xl border border-amber-300 text-xs font-bold text-amber-950 shadow-2xs select-none">
                <input
                  type="checkbox"
                  checked={replaceExisting}
                  onChange={e => setReplaceExisting(e.target.checked)}
                  className="rounded text-amber-600 focus:ring-amber-500 w-4 h-4 cursor-pointer"
                />
                <span>Replace Existing</span>
              </label>
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="p-4 border-t border-slate-100 bg-slate-50 flex items-center justify-between">
          <div className="text-xs text-slate-500">
            Ready to generate <strong className="text-slate-900 font-bold">{activeCandidateList.length} faculty records</strong>
          </div>
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 rounded-xl border border-slate-300 bg-white hover:bg-slate-100 text-slate-700 font-bold text-xs transition cursor-pointer"
            >
              Cancel
            </button>
            <button
              type="button"
              disabled={activeCandidateList.length === 0}
              onClick={handleExecute}
              className="px-5 py-2 rounded-xl bg-gradient-to-r from-indigo-600 to-violet-600 hover:from-indigo-700 hover:to-violet-700 text-white font-bold text-xs shadow-md shadow-indigo-500/20 disabled:opacity-50 disabled:cursor-not-allowed transition cursor-pointer flex items-center gap-1.5"
            >
              <Zap className="w-4 h-4 fill-amber-300 text-amber-300" />
              <span>
                {replaceExisting ? 'Configure' : 'Add'} {activeCandidateList.length} Faculty Members
              </span>
            </button>
          </div>
        </div>

      </div>
    </div>
  );
}
